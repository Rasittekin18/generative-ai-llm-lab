#Word2Vec eğitim
from gensim.models import Word2Vec
from nltk.corpus import stopwords
import multiprocessing
import pandas as pd
import re
from google.colab import drive
import nltk
nltk.download('stopwords')


#Büyük/küçük harfe duyarlı olduğu için tüm kelimelerin küçük harfe dönüştürülmesi için fonksiyon
def kucuk_harf_donustur(metin):
    metin = metin.lower()
    return metin

#Metinden özel karakterlerin temizlenmesi için fonksiyon
def temizle(metin):
    metin = re.sub(r'[^ \nA-Za-z0-9À-ÖØ-öø-ÿ/]+', '', metin)
    metin = re.sub(r'[\\/×\^\]\[÷]', '', metin)
    return metin

#Metinden "and", "the" gibi etkisiz kelimelerin çıkarılması için fonksiyon
def ayikla(metin):
    metin_tokens = metin.split(" ")
    final_list = [word for word in metin_tokens if not word in stopwords_list]
    metin = ' '.join(final_list)
    return metin

#Verinin eğitim için kullanılacak hale dönüştürülmesi
def w2vecdata_d_al(data_d):
    w2vec_data_d = pd.DataFrame(data_d["Description"]).values.tolist()
    for i in range(len(w2vec_data_d)):
        w2vec_data_d[i] = w2vec_data_d[i][0].split(" ")
    return w2vec_data_d

#Word2Vec eğitimi için kullanılacak fonksiyon
def train_w2vec(w2vec_data_d):
    #Daha önce yüklenen Word2Vec eğitim için kullanılacak yapay sinir ağını tanımlıyor
    w2vec_model = Word2Vec(min_count=4,
                         window=4,
                         alpha=0.028,
                         min_alpha=0.0009,
                         sg = 1)
    w2vec_model.build_vocab(w2vec_data_d, progress_per=10000)
    w2vec_model.train(w2vec_data_d, total_examples=w2vec_model.corpus_count, epochs=90, report_delay=1)
    return w2vec_model

#ayikla fonksiyonunda kullanılacak etkisiz kelime listesinin oluşturulması
stopwords_list = stopwords.words("english")

#Word2Vec egitim icin kullanılacak otel yorumlarını içeren train.csv veri kümesinin yüklenmesi
#Veri kümesinin sadece yorumların bulunduğu "Description" kolonu kullanılıyor
drive.mount('/content/gdrive')
file_path = "/content/gdrive/MyDrive/ML/datasets/train.csv"
data_d = pd.read_csv(file_path)


data_d["Description"] = data_d["Description"].astype(str)
data_d["Description"] = data_d["Description"].apply(kucuk_harf_donustur)
data_d["Description"] = data_d["Description"].apply(temizle)
data_d["Description"] = data_d["Description"].apply(ayikla)

w2vec_data_d = w2vecdata_d_al(data_d)
w2vec_model = train_w2vec(w2vec_data_d)

#Eğitilmiş modeli kullanarak gerçekleştirilen bazı örnek fonksiyonlar
print("'old' kelimesine benzer kelimeler:\n",w2vec_model.wv.most_similar(positive=["old"]))
print("'beautiful' kelimesine benzer kelimeler:\n",w2vec_model.wv.most_similar(positive=["beautiful"]))
print("'woman' ve 'man' kelimesi arasındaki benzerlik:\n",w2vec_model.wv.similarity('woman','man'))
print("'woman' ve 'room' kelimesi arasındaki benzerlik:\n",w2vec_model.wv.similarity('woman','room'))
print("'bed' ve 'room' kelimesi arasındaki benzerlik:\n",w2vec_model.wv.similarity('bed','room'))
print("'breakfast', 'room', 'dinner' ve 'lunch' kelimeleri arasında farklı olan:\n", w2vec_model.wv.doesnt_match("breakfast room dinner lunch".split()))
print("'woman' ve 'daughter' kelimeleri arasındaki ilişkinin 'man' ile hangi kelime arasında olduğu:\n",w2vec_model.wv.most_similar(positive=['woman','daughter'],negative=['man'],topn=1))