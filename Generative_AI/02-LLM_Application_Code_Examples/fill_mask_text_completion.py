#Türkçe verilen bir metindeki eksik kelimenin üretilmesi
from transformers import pipeline

#Uygun model seçilerek pipeline oluşturulması
#top_k=4 ile en iyi 4 seçenek getirilmesi isteniyor.
pipeline_1 = pipeline('fill-mask', model='google-bert/bert-base-multilingual-cased',top_k=4)

#pipeline'ın verilen metin için çalıştırılması
#[MASK] eksik kelimeyi gösteriyor, model bu kelimenin yerini alabilecek en iyi 4 seçeneği getiriyor.
sonuc=pipeline_1("Yapay zeka üzerine yapılan çalışmalar son [MASK] çok artmıştır.")
b_st = "\033[1m" #bold yazmayı başlatmak için
b_e = "\033[0;0m" #bold yazmayı bitirmek için
for i in range (len(sonuc)):
  print("Kelime:",b_st,sonuc[i]["token_str"],b_e, "Puan (olasılık yüzdesi):",b_st,"%.2f" %sonuc[i]["score"],b_e)