#Farklı parametreleri kullanarak metin üretme

from transformers import pipeline
b_st = "\033[1m" #bold yazmayı başlatmak için
b_e = "\033[0;0m" #bold yazmayı bitirmek için

#Metin üretimi için gpt2 modelini seçiyoruz ve prompt'umuzu belirliyoruz.
#pad_token_id parametresi "Setting `pad_token_id` to `eos_token_id`:50256 for open-end generation" hatasının gelmesini engellemek için
uretici = pipeline('text-generation', model='gpt2',pad_token_id = 50256)
prompt = "World is seriously threatened by global warming."

#Default değerlerle metin üretilmesi
#Default olarak greedy search yapılır. Greedy search her token için en yüksek olasılıklı seçimi yapar
#temperature parametresi ile token için yapılacak seçimin olasılık olarak daha yüksek ya da düşük yüzdeli seçeneklerden yapılmasını sağlayabiliriz.
#Temperature için 0 değeri verilince en olası metin üretilir.
uretilen_metin = uretici(prompt, max_length=120,truncation=True,temperature=0.0,do_sample=False)[0]['generated_text']
print(b_st,"temperature=0  kullanılarak 1.deneme:\n",b_e,uretilen_metin)

#temperature parametresi için 0 değeri verilerek ikinci deneme yapıldığında, en yüksek olasılıklı seçimler yapıldığından yine aynı metin üretilir.
uretilen_metin = uretici(prompt, max_length=120,truncation=True,temperature=0.0,do_sample=False)[0]['generated_text']
print(b_st,"temperature=0  kullanılarak 2.deneme:\n",b_e,uretilen_metin)

#Temperature parametresi default olarak 1 değerini alır ve buna göre token seçimi olasılıksal dağılıma göre yapılır.
uretilen_metin = uretici(prompt, max_length=120,truncation=True)[0]['generated_text']
print(b_st,"Default parametreler kullanılarak 1.deneme :\n",b_e,uretilen_metin)

#Temperature= 1 ile ikinci kez üretimde, olaslıksal dağılım kullanıldığından farklı metin üretilir.
uretilen_metin = uretici(prompt, max_length=120,truncation=True)[0]['generated_text']
print(b_st,"Default parametreler kullanılarak:2.deneme \n",b_e,uretilen_metin)

#repetition_penalty  parametresine yüksek değer vererek, aynı cümlenin tekrar üretilmesini engelleyebiliriz.
uretilen_metin = uretici(prompt, max_length=120,truncation=True,temperature=0.0,do_sample=False,repetition_penalty=3.0)[0]['generated_text']
print(b_st,"temperature=0 ve repetition_penalty=3.0 kullanılarak :\n",b_e,uretilen_metin)

#num_beams parametresi ile ışın araması yapılmasını sağlar ve seçimin sıradaki tokenın olasılıksal değerlendirilmesi yerine  dizinlerin olasılıksal değerlendirilmesi ile yapılmasını sağlarız.
uretilen_metin = uretici(prompt, max_length=120,truncation=True,temperature=0.0,do_sample=False,repetition_penalty=3.0,num_beams=5)[0]['generated_text']
print(b_st,"num_beams=5 parametresi kullanılarak :\n",b_e,uretilen_metin)

#num_beams parametresi ile beraber num_return_sequences parametresini kullanarak ışın araması ile birden fazla arama yapılmasını sağlar ve içlerinden en uygununu seçebiliriz.
uretilen_metinler = uretici(prompt, max_length=120,truncation=True,temperature=1.2,do_sample=True,top_p=0.75,top_k=5,repetition_penalty=2.0,num_return_sequences=5)
for i in range(5):
  print(b_st,"num_return_sequences=5 parametresi kullanılarak uretilen",i,".metin:\n",b_e,uretilen_metinler[i]['generated_text'])

#do_sample=True parametresi olasılık dağılımı içinden örnekleme ile seçim yapılmasını sağlarız.
#Too_p=0.75 parametresi örnekleme yapılırken olasılıksal dağılımı 0.75'in üzerinde olanlar içinden örnekleme yapılmasını sağlar.
#Too_K=5 parametresi örnekleme yapılırken, olasılılsal dağılımı en yüksek 5 token içinden örnekleme yapılmasını sağlar.
uretilen_metin = uretici(prompt, max_length=120,truncation=True,temperature=1.5,do_sample=True,top_p=0.75,top_k=5,repetition_penalty=2.0)[0]['generated_text']
print(b_st,"do_sample=True,top_p=0.75,top_k=5 parametresi kullanılarak :\n",b_e,uretilen_metin)