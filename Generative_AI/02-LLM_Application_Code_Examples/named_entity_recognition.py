#İsimlendirilmiş varlık tanıma(Named entity recognition-NER)
from transformers import pipeline

#Uygun model seçilerek pipeline oluşturulması
#grouped_entities=True parametresi arka arkaya yer alan NER kelimelerinin bir grup olarak gösterilmesini sağlıyor.
ner_pipeline = pipeline("ner", model ='FacebookAI/xlm-roberta-large-finetuned-conll03-english', grouped_entities=True)

#pipeline'ın verilen metin için çalıştırılması
sonuc= ner_pipeline("Türkiye Büyük Millet Meclisi Ankara'da milletvekillerinin katılımı ile toplandı.")
b_st = "\033[1m" #bold yazmayı başlatmak için
b_e = "\033[0;0m" #bold yazmayı bitirmek için
for i in range (len(sonuc)):
  print("Kelime:", b_st,sonuc[i]["word"],b_e,"Kelime tipi:",b_st,sonuc[i]["entity_group"],b_e, "Puan (olasılık yüzdesi):",b_st,"%.2f" %sonuc[i]["score"],b_e)