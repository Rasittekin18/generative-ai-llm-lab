from transformers import AutoTokenizer, AutoModelForSequenceClassification
from transformers import pipeline

#Seçilen model ile duygu analizinin yapılması
model_ismi= "j-hartmann/emotion-english-distilroberta-base"
# model atamasini yapiyoruz
model = AutoModelForSequenceClassification.from_pretrained(model_ismi)
# Tokenizer model için otomatik olarak belirleniyor
tokenizer = AutoTokenizer.from_pretrained(model_ismi)
# seçtiğimiz model ve onun tokenizeri için sınıflandırıcı ataması yapılıyor
sınıflandırıcı = pipeline("sentiment-analysis", model = model, tokenizer = tokenizer)
sonuc =sınıflandırıcı ("I really like it")
print("Seçilen model ile duygu analizinin sonucu:\n",sonuc,"\n")

# Sınıflandırıcıya sadece yapmasını istediğimiz şeyi söyleyince kendisi bu task için default model seçiyor
sınıflandırıcı2 = pipeline("sentiment-analysis")
sonuc2 = sınıflandırıcı2 ("I really like it")
print("Default model ile duygu analizinin sonucu:\n",sonuc2)