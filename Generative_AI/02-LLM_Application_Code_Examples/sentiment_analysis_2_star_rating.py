# Duygu analizi-2 yorumun 5 yıldızlı değerlendirmeye dönüştürülmesi
from transformers import AutoTokenizer, AutoModelForSequenceClassification
from transformers import pipeline

model_ismi = "nlptown/bert-base-multilingual-uncased-sentiment"

# model atamasini yapiyoruz
model = AutoModelForSequenceClassification.from_pretrained(model_ismi)

# Tokenizer model için otomatik olarak belirleniyor
tokenizer = AutoTokenizer.from_pretrained(model_ismi)

# sectigimiz model ve onun tokenizeri ici sınıflandırıcı ataması yapılıyor
sınıflandırıcı= pipeline("sentiment-analysis", model = model, tokenizer = tokenizer)

girdiler= ["I've been waiting for this training all my life!","that's really amazing!","good experience",
           "don't want to experience again","moderate, no extras","I wish to comment better but not good enough"]
for x in girdiler:
  sonuc = sınıflandırıcı(x)
  print (x,":",sonuc[0]["label"])