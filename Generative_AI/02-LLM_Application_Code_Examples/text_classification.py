#Verilen seçenekler için metnin etiketlenmesi
from transformers import pipeline
import numpy as np

#Modelden sınıflandırıcı pipeline'i oluştur
sınıflandırıcı = pipeline(model="facebook/bart-large-mnli")

#1. örnek verilen etiketlerden hangilerine metnin uyduğunu belirlemek için.
ornek1=sınıflandırıcı(
    "I have an amazing news and want to share it with my parents asap!!",
    candidate_labels=["urgent", "not urgent", "family", "job", "food"],)

#2. örnek verilen dil seçeneklerinden hangilerine metinin uyduğunu belirlemek için.
ornek2=sınıflandırıcı(
    "I have an amazing news and want to share it with my parents asap!!",
    candidate_labels=["english", "german","french"],)
#ornek1 ve ornek2 dictionary veri tipindedir.Sequence, labels ve scores key'lerine sahiptir.
Ornek1_adet= np.size(ornek1['labels'])
Ornek2_adet= np.size(ornek2['labels'])
print ("Örnek 1, verilen başlıklar için sınıflandırma yapılması:")
for x in range(Ornek1_adet):
  print(ornek1['labels'][x]," başlığı için skor" "=", ornek1['scores'][x])
print ("\n Örnek 2,  metin için dil belirlenmesi:")
for x in range(Ornek2_adet):
  print(ornek2['labels'][x]," dili için skor" "=", ornek2['scores'][x])