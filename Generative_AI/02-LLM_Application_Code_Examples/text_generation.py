# Metin üretme
from transformers import pipeline

#Metin üretici modeli yüklüyoruz
uretici = pipeline('text-generation', model='gpt2')

istem = "World is seriously threatened by global warming"


#temperature parametresi default olarak 0 değerini alır ve 0 değeri en olası metini üretir.0'dan büyük değerler aldıkça daha farklı ve az olası metinler üretme şansı artar.
uretilen_metin = uretici(istem, max_length=120,truncation=True,temperature=0.7,num_beams=5,repetition_penalty=3.0)[0]['generated_text']

print(uretilen_metin)