from transformers import pipeline

#Uygun model seçilerek pipeline oluşturulması
pipeline_ozet = pipeline("summarization", model="csebuetnlp/mT5_multilingual_XLSum")

#özetlenecek makale
makale = """"International Journal of Geriatric Psychiatry" dergisinde yayımlanan çalışmaya göre, Exeter Üniversitesinden bilim insanları, müzikle uğraşan ve uğraşmayan kişilerin beyinlerinin nasıl yaşlandığını araştırdı.

Araştırmada, enstrüman çalma, şarkı söyleme, nota okuma, müzik dinleme ve müzik yeteneğinin insan beyni üzerindeki etkileri 40-68 yaş 1100'den fazla kişi üzerinde incelendi.
Araştırmacılar, hayatlarında müzikle uğraşmış ve müzikle hiç ilgilenmemiş kişilerin bilişsel verilerini karşılaştırdı.

Sonuçlar, piyano ya da org çalan kişilerin müzikle uğraşmanın yararını daha fazla gördüğü ancak yalnızca müzik dinlemenin bilişsel sağlığa aynı şekilde etki etmediğini gösterdi."""

#pipeline'ın çalıştırılması
ozet = pipeline_ozet(makale, max_length=40, min_length=20, do_sample=False)
print("Verilen yazinin özeti:\n",ozet[0]["summary_text"])