#Metinden görüntü oluşturma

import requests
import io
from PIL import Image
import IPython.display as display

#huggingface ortamından çağırılacak olan model ve API'si
Model_API = "https://api-inference.huggingface.co/models/stabilityai/stable-diffusion-xl-base-1.0"
#Bearer karşısında XXXXXXXXXXXXXXXXXX olarak gözüken kısma Huggingface'den alacağınız kendi token'ınızı yazmalısınız.
headers = {"Authorization": "Bearer XXXXXXXXXXXXXXXXXXXX"}

#Metini girdi olarak alıp, model API'sini çağıracak fonksiyon
def query(icerik):
	response = requests.post(Model_API, headers=headers, json=icerik)
	return response.content

goruntu_girdi = query({	"inputs": "horses in the middle of green grass",})
# goruntunun gösterilecek hale getirilmesi
goruntu = Image.open(io.BytesIO(goruntu_girdi))
display.display(goruntu)