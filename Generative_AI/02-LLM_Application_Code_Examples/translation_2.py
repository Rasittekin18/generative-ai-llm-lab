from transformers import T5Tokenizer, T5ForConditionalGeneration

#Tokenizer'i tanımla
tokenizer = T5Tokenizer.from_pretrained("t5-small")

#Model'i tanımla
model = T5ForConditionalGeneration.from_pretrained("t5-small")

#Prompt'u da içeren tercüme edilecek metinler
girdiler = ["translate English to French: The weather will be sunny tomorrow.",
            "translate English to German: The weather will be sunny tomorrow."]

for x in girdiler:
  #Tokenlara ayır
  girdi_token = tokenizer(x, return_tensors="pt").input_ids
  #Tokena dönüştürülmüş girdilerin modele verilerek çıktının üretilmesi
  cikti_token = model.generate(girdi_token)
  #Tokenlardan oluşan çıktıdan cümle başı, cümle sonu gibi tokenlar çıkarılması ve metne dönüştürülmesi
  cikti = tokenizer.decode(cikti_token[0], skip_special_tokens=True)
  print(x,"-->",cikti)