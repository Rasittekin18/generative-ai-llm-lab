# Metin siniflandirici
from transformers import pipeline

#Metin sınıflandırıcı modeli yüklüyoruz
sınıflandırıcı = pipeline("text-classification",model='lxyuan/distilbert-base-multilingual-cased-sentiments-student')

girdiler= ["işimden çok memnunum","Yediğim en kötü yemeklerden birisiydi",
           "Uzun zamandır böyle güzel bir film seyretmemiştim"]
for x in girdiler:
  sonuc = sınıflandırıcı(x)
  print (x,":",sonuc[0]["label"])