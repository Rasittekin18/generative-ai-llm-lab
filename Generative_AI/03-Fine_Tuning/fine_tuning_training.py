from datasets import load_dataset
from transformers import AutoTokenizer, DataCollatorWithPadding
import numpy as np
from transformers import TrainingArguments
from transformers import AutoModelForSequenceClassification
from transformers import Trainer
import evaluate
import numpy as np

#Veri setindeki her örnek için iki cümleyi tokenlara dönüştüren fonksiyon
def tokenize_function(example):
    return tokenizer(example["sentence1"], example["sentence2"], truncation=True)

#ince ayar için seçilen veri setinin yüklenmesi
veri_seti = load_dataset("glue", "mrpc")

#ince ayar yapılacak olan öneğitim yapılmış olan model
model_ismi = "bert-base-uncased"

#model ismine uygun tokenizerın seçilmesi
tokenizer = AutoTokenizer.from_pretrained(model_ismi)

# veri setinden, tokenize veri setinin oluşturulması
tokenized_datasets = veri_seti.map(tokenize_function, batched=True)

#Datacollator verinin ince ayar eğitim öncesi, padding ve bunun gibi benzer işlemlerden geçirilerek aynı uzunluk ve aynı formata getirilmesini sağlar.
data_collator = DataCollatorWithPadding(tokenizer=tokenizer)

#Egitim, dogrulama (validation) ve test veri setlerinin egitim zamanını dusuk tutmak icin az sayida ornek ile oluşturulması
egitim_dataset = tokenized_datasets["train"].shuffle(seed=42).select(range(200))
validation_dataset = tokenized_datasets["validation"].shuffle(seed=42).select(range(80))
test_dataset = tokenized_datasets["test"].shuffle(seed=42).select(range(80))

#eğitim argümanı olarak verilen "test-trainer" yeni modelin kaydedileceği directory'i gösterir.
#eğitim argümanı olarak verilen evaluation_strategy, modelin performans ölçümünün her epoch'da yani veri setinin tamamının eğitim için kullanımı sonrasında yapılacağını gösterir.
training_args = TrainingArguments("test-trainer", evaluation_strategy="epoch")

#Ön eğitimli modelimizin, hangi fonksiyon için (sequence classification) ince ayar yapılacağını belirliyoruz.
model = AutoModelForSequenceClassification.from_pretrained(model_ismi, num_labels=2)

#ince ayar eğitim için gerekli parametreleri veriyoruz
trainer = Trainer(model,
    training_args,
    train_dataset=egitim_dataset,
    eval_dataset=validation_dataset,
    data_collator=data_collator,
    tokenizer=tokenizer,
)
#ince ayar eğitimi yapıyoruz
trainer.train()

#eğitim veri setinin eğitimde kullanmadığımız test veri seti ile artık eğitilmiş olan modelimiz üzerinden tahminler oluşturuyoruz.
predictions = trainer.predict(test_dataset)

#eğitilmiş modelimiz iki etiket değeri için olasılık değerleri bulur, bunun büyük olanını modelin tahmini olarak alıyoruz.
preds = np.argmax(predictions.predictions, axis=-1)


# Kullanilacak veri setine uygun metriklerin yüklenmesi
metric = evaluate.load("glue", "mrpc")
#Performans değerlerinin ölçülmesi
metric.compute(predictions=preds, references=predictions.label_ids)