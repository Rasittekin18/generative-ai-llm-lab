#Gerekli kütüphanelerin yüklenmesi
from langchain.agents import initialize_agent
from langchain.agents import AgentType
from langchain.agents import load_tools
from langchain.agents import initialize_agent
from langchain.agents import AgentType, Tool
import os
from google.colab import userdata
from langchain_community.llms import HuggingFaceEndpoint
from langchain.chains import LLMChain




#Huggingface token'ın yüklenmesi
HUGGINGFACEHUB_API_TOKEN = userdata.get('hugging_face_token')
os.environ["HUGGINGFACEHUB_API_TOKEN"] = HUGGINGFACEHUB_API_TOKEN


#Huggingface hubdan kullanılacak modelin tanımlanması
model_ismi = "mistralai/Mistral-7B-Instruct-v0.2"

#llm'in Huggingface hub üzerinden kullanılması
llm = HuggingFaceEndpoint(
    repo_id=model_ismi,
    temperature = 0.5,
    model_kwargs={"max_length": 610,"token": HUGGINGFACEHUB_API_TOKEN}
)

#Google searchapi key'inin yüklenmesi

os.environ["SERPAPI_API_KEY"] = userdata.get('serpapi_key')

#agent için kullanılacak araçların tanımlanması
tools = load_tools(["pubmed","wikipedia", "serpapi","llm-math"], llm=llm)

#agent'ın oluşturulması
agent = initialize_agent(tools,
                         llm,
                         agent=AgentType.ZERO_SHOT_REACT_DESCRIPTION,
                         handle_parsing_errors=True,
                         verbose=True)
agent.run("What medicenes should be used to treat Covid-19")

agent.run("What is the result of 25 times 6 divided by 10? ")