#Gerekli kütüphanelerin yüklenmesi
from langchain.prompts import PromptTemplate
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM,pipeline
from langchain_community.llms import HuggingFacePipeline
from langchain import LLMChain
from langchain_core.output_parsers import StrOutputParser
from langchain.chains import SequentialChain
from langchain_community.llms import HuggingFaceEndpoint
import os

#Modelin Huggingface API'i ile Hugginfaceendpoint'den kullanılması için Huggingface token kullanılıyor.
#Burada xxx yerine kendi token'ınızı girmelisiniz
os.environ["HUGGINGFACEHUB_API_TOKEN"] = "xxx"

b_st = "\033[1m" #bold yazmayı başlatmak için
b_e = "\033[0;0m" #bold yazmayı bitirmek için

#1. istem şablonunun hazırlanması
prompt = PromptTemplate(
    input_variables=["thing","country"],
    template="What is the most popular {thing} in {country}?Just tell the most popular one with only one word.",
)
print("İstem şablonunu değişkenleri yerleştirerek oluşturulan istem1\n", prompt.format(thing ="food", country="Italy"),"\n")

#Birinci Dil modeli ve tokenizer'ın yüklenmesi ve dil modelinin tanımlanması
tokenizer = AutoTokenizer.from_pretrained("google/flan-t5-base")
model = AutoModelForSeq2SeqLM.from_pretrained("google/flan-t5-base")
pipe = pipeline("text2text-generation", model=model, tokenizer=tokenizer,max_new_tokens=1000)
hf = HuggingFacePipeline(
    pipeline = pipe,
    model_kwargs={"temperature": 0, "max_length": 610},
)
llm1 = hf


#İkinci Dil modelinin tanımlanması
model = "mistralai/Mistral-7B-Instruct-v0.2"
llm2 = HuggingFaceEndpoint(repo_id=model, temperature=0.5, model_kwargs={"max_length": 512})


#Birinci zincirin oluşturulması
llmchain1 = LLMChain(llm=llm1, prompt=prompt,output_key = "cikti1")
llm1_cikti = llmchain1.run({"thing": "food", "country": "Italy"})
print(b_st,"Birinci zincirin çıktısı:",b_e,llm1_cikti)


#2. istem şablonunun hazırlanması
prompt2 = PromptTemplate(
    input_variables=["cikti1"],
    template="what are the some popular types of {cikti1}?",
)
print(b_st,"İstem şablonunu değişkenleri yerleştirerek oluşturulan istem2:\n",b_e, prompt2.format(cikti1 = llm1_cikti),"\n")


#İkinci zincirin oluşturulması
llmchain2= LLMChain(llm=llm2, prompt=prompt2)


#Sıralı zincirin oluşturulması
complete_chain = SequentialChain(
    chains=[llmchain1, llmchain2],
    input_variables=["thing", "country"],
    verbose=True,
)

#Sıralı zincirin çalıştırılması
cikti_all = complete_chain.run({"thing": "food", "country": "Italy"})
print (b_st,"Bütün zincirin çalışması durumunda",b_e,cikti_all)