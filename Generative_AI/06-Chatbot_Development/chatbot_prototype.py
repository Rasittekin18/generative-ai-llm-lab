from together import Together
import os
from google.colab import userdata

#Together token'ın yüklenmesi
TOGETHER_API_KEY = userdata.get('together_key')
os.environ["TOGETHER_API_KEY"]=TOGETHER_API_KEY

client = Together()

print("Chatbot application (type 'quit' to exit)")
# messages list'i içinde konuşma geçimişini sakla
messages = []
while True:
    # Kullanıcı girdisini al
    kullanici_girdisi = input("You: ")
    # "quit" komutunu kontrol et
    if kullanici_girdisi.lower() == 'quit':
        print("Goodbye!")
        break
    # Messages list'ine kullanıcı istemini ekle
    messages.append({"role": "user", "content": kullanici_girdisi})
    try:
        # Bot cevabını al
        response = client.chat.completions.create(
        model="meta-llama/Llama-3.3-70B-Instruct-Turbo",
        messages=messages, )
        # Bot mesajını ekrana bastır
        bot_message = response.choices[0].message.content
        print(bot_message)
        # Messages list'ine bot mesajını ekle
        messages.append({"role": "assistant", "content": bot_message})
    except Exception as e:
        print(f"error occurred: {e}")