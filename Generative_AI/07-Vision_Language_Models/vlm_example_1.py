#orijinal Colabde Example4_image_text_text_from_string.ipynb
import torch
from transformers import pipeline
from google.colab import drive
import os
import base64

#Görüntü dosyasının gdrive'dan yüklenmesi
drive.mount('/content/gdrive')
file_path = "/content/gdrive/MyDrive/ML/images/vlm_example_image.png"

#Görüntü dosyasının byte string'e çevrilmesi
with open(file_path, "rb") as image_file:
    encoded_string = base64.b64encode(image_file.read()).decode('utf-8')
_, extension = os.path.splitext(file_path)
mime_type = f"image/{extension[1:].lower()}"
image_data= f"data:{mime_type};base64,{encoded_string}"

#Model bilgisiyle pipeline objesinin yaratılması
pipeline = pipeline("image-text-to-text", model="llava-hf/llava-onevision-qwen2-0.5b-ov-hf", torch_dtype=torch.float16)
prompt = "what are these?"

#List tipindeki messages objesi oluşturuluyor.
#Messages değişkeni içinde text tipinde prompt ve image_url tipinde görüntü dosyasının byte string'e çevrilmiş hali tanımlanıyor.
messages = [
    {
        "role": "user",
        "content": [{"type": "text", "text": prompt}, {"type": "image_url", "image_url": {"url": image_data}}]
    },
]
#pipeline objesi, messages objesi girdi olarak verilerek çalıştırılıyor.
pipeline(text=messages, max_new_tokens=100, return_full_text=False)