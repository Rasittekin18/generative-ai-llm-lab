import torch
from PIL import Image
from transformers import AutoModel, AutoTokenizer

from google.colab import drive

#Görüntü dosyasının gdrive'dan yüklenmesi
drive.mount('/content/gdrive')
file_path = "/content/gdrive/MyDrive/ML/images/Fatura_ornegi.png"

#Modelin yüklenmesi
model = AutoModel.from_pretrained('openbmb/MiniCPM-Llama3-V-2_5', trust_remote_code=True, torch_dtype=torch.float16)

#Tokenizer'ın yüklenmesi
tokenizer = AutoTokenizer.from_pretrained('openbmb/MiniCPM-Llama3-V-2_5', trust_remote_code=True)
#Modelin çıkarım (inference) modunda kullanılması
model.eval()

goruntu = Image.open(file_path).convert('RGB')
question = 'Please answer the following questions by using information in the image. Question1 What is the invoice number? Question2: What is the invoice date? Question3: What is the invoice balance due??'
messages = [{'role': 'user', 'content': question}]

with torch.no_grad():  # Gradyan hesaplamalarının devre dışı bırakılarak daha hızlı çalışmasının sağlanması
    res = model.chat(image=goruntu,msgs=messages,tokenizer=tokenizer,sampling=True,temperature=0.7,)

print("Sonuc:",res)