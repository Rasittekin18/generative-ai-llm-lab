from transformers import AutoTokenizer

tokenizer = AutoTokenizer.from_pretrained("gpt2")

from transformers import AutoModelForCausalLM

model = AutoModelForCausalLM.from_pretrained("gpt2")

model.generation_config.pad_token_id = model.generation_config.eos_token_id

input_prompt = "I enjoy walking with my cute dog"

model_inputs = tokenizer(input_prompt, return_tensors="pt")

model_inputs

greedy_output = model.generate(
    **model_inputs,
    max_new_tokens = 40,
)

print(tokenizer.decode(
    greedy_output[0],
    skip_special_tokens = True
))

beam_output = model.generate(
    **model_inputs,
    max_new_tokens = 40,
    num_beams = 5,
    early_stopping = True,
)

print(tokenizer.decode(
    beam_output[0],
    skip_special_tokens = True
))

beam_output = model.generate(
    **model_inputs,
    max_new_tokens = 40,
    num_beams = 5,
    early_stopping = True,
    no_repeat_ngram_size = 2,
)

print(tokenizer.decode(
    beam_output[0],
    skip_special_tokens = True
))

beam_output = model.generate(
    **model_inputs,
    max_new_tokens = 40,
    num_beams = 5,
    early_stopping = True,
    no_repeat_ngram_size = 2,
    num_return_sequences = 5,
)

for i, beam_output in enumerate(beam_output):
  print(f"{i}, {tokenizer.decode(beam_output, skip_special_tokens=True)}")

